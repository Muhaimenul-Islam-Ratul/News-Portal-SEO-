export const ALL_TOPICS: SeoTopic[] = SEO_SECTIONS.flatMap(section => section.topics);

export function getTopicById(id: string): SeoTopic | undefined {
  return ALL_TOPICS.find(t => t.id === id);
}

export function searchTopics(query: string): SeoTopic[] {
  if (!query.trim()) return ALL_TOPICS;
  const q = query.toLowerCase().trim();
  return ALL_TOPICS.filter(t => 
    t.titleBn.toLowerCase().includes(q) ||
    t.titleEn.toLowerCase().includes(q) ||
    t.summary.toLowerCase().includes(q) ||
    t.category.toLowerCase().includes(q)
  );
}
